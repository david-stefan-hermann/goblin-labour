#!/usr/bin/env python
"""Turn the raw TTS clips into mod assets and keep the mod's line tables in sync with lines.json.

Deterministic and idempotent; needs only ffmpeg (no torch). Run after generate.py, or on its own whenever
voice.json's `post` filters or lines.json change:

    python build.py            # render oggs, update sounds.json, lang files and GoblinLines.java
    python build.py --check    # report only, change nothing

Per line in lines.json:
  raw/<id>.wav  --ffmpeg-->  src/main/resources/assets/goblinlabour/sounds/goblin/line/<id>.ogg (mono Vorbis)
  sound event   entity.goblin.line.<id>   (only for lines that have a raw clip)
  Java          GoblinLines.<GROUP>       (every line, voiced or not; unvoiced lines fall back to the group sound)
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MOD = HERE.parent.parent
RAW = HERE / "raw"
ASSETS = MOD / "src/main/resources/assets/goblinlabour"
OGG_DIR = ASSETS / "sounds/goblin/line"
SOUNDS_JSON = ASSETS / "sounds.json"
LANG_DIR = ASSETS / "lang"
JAVA_OUT = MOD / "src/main/java/goblinlabour/GoblinLines.java"

EVENT_PREFIX = "entity.goblin.line."
SUBTITLE_KEY = "subtitles.goblinlabour.goblin.line"
SUBTITLES = {"en_us": "Goblin talks", "de_de": "Goblin redet"}


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def dump(path, data):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")


def render(raw, ogg, post):
    cmd = [
        "ffmpeg", "-y", "-loglevel", "error", "-i", str(raw),
        "-af", post["filters"], "-ac", "1", "-ar", str(post["sample_rate"]),
        "-c:a", "libvorbis", "-q:a", str(post["vorbis_quality"]), str(ogg),
    ]
    subprocess.run(cmd, check=True)


def java_string(s):
    return json.dumps(s, ensure_ascii=True)


def write_java(lines, voiced):
    groups = {}
    for line in lines:
        groups.setdefault(line["group"], []).append(line)
    out = [
        "// Generated by art/voice/build.py from art/voice/lines.json. Do not edit; edit lines.json and rerun.",
        "package goblinlabour;",
        "",
        "import goblinlabour.GoblinSpeech.Line;",
        "",
        "/** Every line a goblin can say, with its voice clip where one has been recorded. */",
        "public final class GoblinLines {",
    ]
    for group, members in groups.items():
        if len(members) == 1:
            m = members[0]
            out.append(f"    public static final Line {group} = line({java_string(m['id'])}, {java_string(m['text'])}, {str(m['id'] in voiced).lower()});")
        else:
            out.append(f"    public static final Line[] {group} = {{")
            for m in members:
                out.append(f"            line({java_string(m['id'])}, {java_string(m['text'])}, {str(m['id'] in voiced).lower()}),")
            out.append("    };")
    out += [
        "",
        "    private GoblinLines() {",
        "    }",
        "",
        "    /** Forces the static initialiser, which registers the sound events. */",
        "    public static void init() {",
        "    }",
        "",
        "    private static Line line(String id, String text, boolean voiced) {",
        f"        return new Line(id, text, voiced ? GoblinSounds.register({java_string(EVENT_PREFIX)} + id) : null);",
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="report only, change nothing")
    args = ap.parse_args()

    lines = load(HERE / "lines.json")["lines"]
    post = load(HERE / "voice.json")["post"]
    ids = [l["id"] for l in lines]
    if len(set(ids)) != len(ids):
        sys.exit("duplicate ids in lines.json")

    voiced = {l["id"] for l in lines if (RAW / f"{l['id']}.wav").exists()}
    missing = [i for i in ids if i not in voiced]
    print(f"{len(lines)} lines, {len(voiced)} with a raw clip, {len(missing)} without: {' '.join(missing) or '-'}")
    if args.check:
        return

    OGG_DIR.mkdir(parents=True, exist_ok=True)
    for i in sorted(voiced):
        render(RAW / f"{i}.wav", OGG_DIR / f"{i}.ogg", post)
    stale = [p for p in OGG_DIR.glob("*.ogg") if p.stem not in voiced]
    for p in stale:
        p.unlink()
    print(f"rendered {len(voiced)} ogg files, removed {len(stale)} stale")

    sounds = load(SOUNDS_JSON)
    sounds = {k: v for k, v in sounds.items() if not k.startswith(EVENT_PREFIX)}
    for i in ids:
        if i in voiced:
            sounds[EVENT_PREFIX + i] = {"subtitle": SUBTITLE_KEY, "sounds": [{"name": f"goblinlabour:goblin/line/{i}"}]}
    dump(SOUNDS_JSON, sounds)

    for lang, text in SUBTITLES.items():
        path = LANG_DIR / f"{lang}.json"
        data = load(path)
        if data.get(SUBTITLE_KEY) != text:
            data[SUBTITLE_KEY] = text
            dump(path, data)

    JAVA_OUT.write_text(write_java(lines, voiced), encoding="utf-8", newline="\n")
    print(f"wrote {SOUNDS_JSON.name}, lang subtitles and {JAVA_OUT.name}")


if __name__ == "__main__":
    main()
